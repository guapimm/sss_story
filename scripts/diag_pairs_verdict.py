"""对 6 条报警逐条判定真伪，并**实测**既有容错匹配器能否正确区分。

## 6 条报警（21 对真实数据里）

| # | 书 | 本章结束 | 下一章开始 | 人工判读 |
|---|---|---|---|---|
| 1 | 12 | 秦牧的柴房 | 杂役坊柴房区 | 共享「柴房」→ 疑似同区域 |
| 2 | 12 | 秦牧的柴房 | 青阳宗外门废料处理池 | **真换场**（毫无共享） |
| 3 | 13 | 上海某三甲医院住院部外 | 仁华医院法务部办公室门口 | 不同部门（医院名还变了） |
| 4 | 13 | 仁华医院…临时安全病房 | 仁华医院…临时安全病房**外** | **同一地点**（只是门外） |
| 5 | 15 | 铁门关驿丞署·院内 | 铁门关驿丞署·前堂 | **同一驿站**（不同房间） |
| 6 | 16 | **市**公安局地下特殊物证库入口走廊 | **市局**地下特殊物证库入口走廊 | **同一地点**（纯缩写） |

→ 4/6 是**假阳性**（#1/#4/#5/#6），#2/#3 应保留报警。

## 关键：项目里**已有**一个经过实战的容错匹配器

`skeleton_planner._mentions()`（主名拆分 + LCS≥4）—— 它正是为解决
"同类假阳性"而建，且已因真实假阳性**加固过两次**。

**不要再写第二个模糊匹配器** —— 本项目反复踩到
"两处实现漂移"（枚举冲突、`_classify` 与 CLI 口径分叉、e2e 绕过配置）。
复用同一个，阈值也只有一个来源。
"""

from __future__ import annotations

import sys

sys.path.insert(0, "src")

from storyforge.domain.outline import WorldStateSnapshot  # noqa: E402
from storyforge.graph.nodes.skeleton_planner import (  # noqa: E402
    _MENTION_MIN_LCS,
    _lcs_len,
    _mentions,
    _normalize_for_match,
)

CASES: list[tuple[int, str, str, bool]] = [
    # (书, 本章结束, 下一章开始, 人工判定"是否真换场")
    (12, "秦牧的柴房", "杂役坊柴房区", False),
    (12, "秦牧的柴房", "青阳宗外门废料处理池", True),
    (13, "上海某三甲医院住院部外", "仁华医院法务部办公室门口", True),
    (13, "仁华医院为王女士安排的临时安全病房",
         "仁华医院为王女士安排的临时安全病房外", False),
    (15, "铁门关驿丞署·院内", "铁门关驿丞署·前堂", False),
    (16, "市公安局地下特殊物证库入口走廊",
         "市局地下特殊物证库入口走廊", False),
]

print("=" * 100)
print(f"用既有的 `_mentions` 匹配器复算（LCS 阈值 = {_MENTION_MIN_LCS}）")
print("=" * 100)
print(f"{'书':<4}{'判定':<10}{'LCS':<6}{'按 _mentions':<14}{'真换场?':<10}{'结论'}")
print("-" * 100)

ok = bad = 0
for bid, a, b, truly_changed in CASES:
    # 语义：`_mentions(b, a)` = "b 里提到了 a" → 视为同一地点 → 不报警
    same_place = _mentions(b, a)
    would_flag = not same_place
    correct = would_flag == truly_changed
    if correct:
        ok += 1
    else:
        bad += 1
    lcs = _lcs_len(_normalize_for_match(b), _normalize_for_match(a))
    print(f"{bid:<4}{'真换场' if truly_changed else '同地点':<10}"
          f"{lcs:<6}{'同地点' if same_place else '报警':<14}"
          f"{'是' if truly_changed else '否':<10}"
          f"{'✅' if correct else '★错'}")

print("-" * 100)
print(f"正确 {ok}/{len(CASES)}，错误 {bad}/{len(CASES)}")
print()
print("=" * 100)
print("结论")
print("=" * 100)
if bad == 0:
    print(
        "  ✅ 既有 `_mentions`（主名拆分 + LCS≥4）能**正确区分**全部 6 条：\n"
        "     · #4/#5/#6 共享长片段 → 判为同地点 → 消掉假阳性\n"
        "     · #2 无共享 / #3 只共享「医院」2 字（< 4）→ 仍报警（正确）\n"
        "\n"
        "  → 修法：连续性检查**复用同一个匹配器**，不新写第二个。\n"
        "     阈值单一来源，也避免『两处实现漂移』（本项目反复踩到的坑）。"
    )
else:
    print(
        f"  ⚠️ 有 {bad} 条判错 —— **不能直接套用**，需先弄清是哪一类：\n"
        "     是阈值问题（LCS 4 太高/太低），还是语义问题（该用别的手段）。\n"
        "     D-16：**先看数据再动手**，不得直接调阈值。"
    )

print()
print("=" * 100)
print("逐条诊断判错的那条（禁止直接调阈值，先定性）")
print("=" * 100)
print(
    "  判错的：书12「秦牧的柴房」→「杂役坊柴房区」\n"
    "    · 共享片段只有「柴房」= 2 字 < 阈值 4 → 按 `_mentions` 会报警\n"
    "    · 人工判读：这是**同一类建筑的不同叫法**（柴房 / 柴房区），\n"
    "      但严格说「秦牧的柴房」是**个人住所**，「杂役坊柴房区」是**集体区域** ——\n"
    "      两者**不是**同一个地点，是**相邻/同类**地点。\n"
    "\n"
    "  ★ 关键判断：这一条**到底该不该报警？**\n"
    "    · 若算『同地点』 → 需要把 LCS 降到 2，但那样 #3（真换场，LCS 也是 2，\n"
    "      共享「医院」）会被**一起放过** → **制造假阴性**。\n"
    "      **两个案例的 LCS 完全相同（都是 2），无法用阈值区分。**\n"
    "    · 若算『真换场』 → 现行判据**已经是对的**，不需要改。\n"
    "\n"
    "  → 这正是 D-16 要防的「调阈值」陷阱：\n"
    "     降阈值能修好 1 条，却会同时弄坏另一条**同样重要**的。\n"
    "     而这两条在**字符串层面不可区分**（LCS 都=2）——\n"
    "     说明『是否同地点』本质上需要**语义/层级**信息，"
    "不是字符串阈值能解决的。"
)
